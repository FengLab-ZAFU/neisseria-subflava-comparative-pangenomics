def _mean_sd(values):
    import statistics
    if not values:
        return "NA", "NA"
    return f"{statistics.mean(values):.6f}", f"{statistics.pstdev(values):.6f}"


def build_mge_gi_descriptive():
    """Build mge_gi_descriptive_by_group.tsv from 09 interval tables."""
    meta_overall = {r["strain"]: r for r in read_tsv(os.path.join(P, "00_cohort/metadata_overall152.tsv"))}
    meta_comp = {r["strain"]: r for r in read_tsv(os.path.join(P, "00_cohort/metadata_comparison144.tsv"))}
    boundary = set(meta_overall) - set(meta_comp)
    psm = {r["accession"]: r for r in read_tsv(os.path.join(OUT08, "participant_subset_manifest.tsv"))}

    pfeat = read_tsv(os.path.join(R, "08_defense_mge_vfdb/per_genome_features.tsv"))
    occ = read_tsv(overlap_input("occurrence_overlap.tsv"))

    # scope definitions
    scopes = {}
    scopes["overall152"] = list(meta_overall.keys())
    scopes["sensitivity152_subflava"] = [a for a, r in meta_overall.items() if r["group_for_testing"] == "subflava"]
    scopes["sensitivity152_perflava"] = [a for a, r in meta_overall.items() if r["group_for_testing"] == "perflava"]
    scopes["sensitivity152_flavescens"] = [a for a, r in meta_overall.items() if r["group_for_testing"] == "flavescens"]
    scopes["primary144_subflava"] = [a for a, r in meta_comp.items() if r["group_for_testing"] == "subflava"]
    scopes["primary144_perflava"] = [a for a, r in meta_comp.items() if r["group_for_testing"] == "perflava"]
    scopes["primary144_flavescens"] = [a for a, r in meta_comp.items() if r["group_for_testing"] == "flavescens"]
    scopes["descriptive8"] = list(boundary)
    scopes["participant_subset_from144"] = [a for a, r in psm.items() if int(r["selected"]) == 1]

    pfeat_by_acc = {r["accession"]: r for r in pfeat}
    contig_counts = {a: int(r["n_contigs"]) for a, r in meta_overall.items()}

    def sum_over(scope, key, present_only=False):
        vals = []
        for a in scopes[scope]:
            r = pfeat_by_acc.get(a)
            if r is None:
                continue
            v = r.get(key, "")
            if v == "":
                continue
            if present_only:
                vals.append(int(v) > 0)
            else:
                vals.append(int(v))
        return vals

    rows = []
    for scope, accs in scopes.items():
        n = len(accs)
        # genome-level descriptors
        total_len = sum(int(meta_overall[a]["genome_size"]) for a in accs if a in meta_overall)
        contig_total = sum(contig_counts[a] for a in accs)
        rows.append({"analysis_scope": scope, "feature": "n_genomes", "n_evaluable": n,
                     "count": n, "per_genome_mean": "NA", "per_genome_sd": "NA",
                     "status": "OK", "note": ""})
        rows.append({"analysis_scope": scope, "feature": "n_contigs", "n_evaluable": n,
                     "count": contig_total, "per_genome_mean": _mean_sd([contig_counts[a] for a in accs])[0],
                     "per_genome_sd": _mean_sd([contig_counts[a] for a in accs])[1],
                     "status": "OK", "note": ""})
        rows.append({"analysis_scope": scope, "feature": "total_genome_length_bp", "n_evaluable": n,
                     "count": total_len, "per_genome_mean": f"{total_len / n:.1f}",
                     "per_genome_sd": "NA", "status": "OK", "note": ""})

        # MGE features
        for feat, key, present in [
            ("n_insertion_sequences", "isescan_is_count", False),
            ("n_integrons", "integron_count", False),
            ("n_proviruses_genomad", "genomad_provirus_count", False),
            ("n_plasmid_contigs_genomad", "genomad_plasmid_contig_count", False),
            ("n_virus_contigs_genomad", "genomad_virus_contig_count", False),
            ("n_plasmid_contigs_mob_suite", "mob_suite_plasmid_contig_count", False),
            ("n_genomic_islands", "islandpath_gi_count", False),
        ]:
            vals = sum_over(scope, key, present_only=present)
            ne = min(n, len(vals))
            total = sum(vals)
            rows.append({"analysis_scope": scope, "feature": feat, "n_evaluable": ne,
                         "count": total, "per_genome_mean": _mean_sd(vals)[0],
                         "per_genome_sd": _mean_sd(vals)[1],
                         "status": "OK" if ne == n else "PARTIAL",
                         "note": ""})

        # GI total length
        gi_total = 0
        for a in accs:
            r = pfeat_by_acc.get(a)
            if r:
                gi_total += int(r.get("gi_total_length_bp", 0) or 0)
        rows.append({"analysis_scope": scope, "feature": "gi_total_length_bp", "n_evaluable": n,
                     "count": gi_total, "per_genome_mean": f"{gi_total / n:.1f}",
                     "per_genome_sd": "NA", "status": "OK", "note": ""})

        # gene-level descriptors from occurrence map
        scope_occ = [r for r in occ if r["accession"] in accs]
        n_genes = len(scope_occ)
        n_mge_overlap = sum(int(r.get("mge_overlap_union_bp", 0) or 0) > 0 for r in scope_occ)
        n_gi_overlap = sum(r.get("gi_half_gene", "") == "TRUE" for r in scope_occ)
        rows.append({"analysis_scope": scope, "feature": "n_genes_in_occurrence_map", "n_evaluable": n,
                     "count": n_genes, "per_genome_mean": f"{n_genes / n:.1f}",
                     "per_genome_sd": "NA", "status": "OK", "note": ""})
        rows.append({"analysis_scope": scope, "feature": "n_genes_with_mge_overlap", "n_evaluable": n_genes,
                     "count": n_mge_overlap, "per_genome_mean": f"{n_mge_overlap / n:.1f}" if n else "NA",
                     "per_genome_sd": "NA", "status": "OK", "note": ""})
        rows.append({"analysis_scope": scope, "feature": "n_genes_with_gi_overlap", "n_evaluable": n_genes,
                     "count": n_gi_overlap, "per_genome_mean": f"{n_gi_overlap / n:.1f}" if n else "NA",
                     "per_genome_sd": "NA", "status": "OK", "note": ""})

    write_tsv(os.path.join(OUT08, "mge_gi_descriptive_by_group.tsv"),
              ["analysis_scope", "feature", "n_evaluable", "count",
               "per_genome_mean", "per_genome_sd", "status", "note"], rows)
    print(f"[D2] mge_gi_descriptive_by_group: {len(rows)} rows")


