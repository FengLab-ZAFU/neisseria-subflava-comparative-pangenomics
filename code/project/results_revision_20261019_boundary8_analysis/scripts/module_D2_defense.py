def build_participant_manifest():
    """Reproduce participant_subset_manifest.tsv from comparison144 metadata.

    Group key: (study_namespace, participant_id) unless participant_id is
    unknown/empty/NA, in which case the accession is a singleton.
    Representative ranking: completeness desc, contamination asc, N50 desc,
    n_contigs asc, accession lexicographic.
    """
    meta = {r["strain"]: r for r in read_tsv(os.path.join(P, "00_cohort/metadata_comparison144.tsv"))}
    # Assembly covariates were calculated from the bound annotation-input FASTAs.
    asm = {r["accession"]: r for r in read_tsv(os.path.join(
        R, "00_freeze/input_packet_snapshot/00_input/reference_sources/assembly_covariates_main152.tsv"))}
    chk = {r["accession"]: r for r in read_tsv(os.path.join(
        R, "00_freeze/input_packet_snapshot/00_input/reference_sources/checkm2_main152.tsv"))}

    groups = defaultdict(list)
    for acc, r in meta.items():
        pid = r["participant_id"].strip()
        if pid in ("", "unknown", "NA"):
            key = json.dumps(["__accession__", acc])
        else:
            key = json.dumps([r["study_namespace"], pid])
        groups[key].append(acc)

    rows = []
    for key, accs in sorted(groups.items()):
        def rank(a):
            return (-float(chk[a]["Completeness"]), float(chk[a]["Contamination"]),
                    -int(asm[a]["n50_bp_p1"]), int(asm[a]["n_contigs_p1"]), a)
        ordered = sorted(accs, key=rank)
        for i, a in enumerate(ordered):
            m = meta[a]
            rows.append({
                "accession": a,
                "participant_key": key,
                "species_group": m["group_for_testing"],
                "rank_in_participant": i + 1,
                "selected": 1 if i == 0 else 0,
                "reason": "highest prespecified quality rank" if i == 0 else "lower prespecified quality rank",
                "n_in_participant": len(accs),
            })

    write_tsv(os.path.join(OUT08, "participant_subset_manifest.tsv"),
              ["accession", "participant_key", "species_group", "rank_in_participant",
               "selected", "reason", "n_in_participant"], rows)
    selected = [r for r in rows if r["selected"] == 1]
    print(f"[D2] participant_subset_manifest: {len(rows)} rows, {len(selected)} selected")
    return {r["accession"]: r for r in rows}


